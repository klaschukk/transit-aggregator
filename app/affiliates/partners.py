# Our (Serbian) city slug -> Bookaway's English slug, ONLY where they differ.
# Bookaway pair pages live at /routes/{from_country}/{from_en}-to-{to_en} and
# use English slugs, so 'beograd' must become 'belgrade' or the pair 404s.
# Cities whose Bookaway slug equals ours (nis, novi-sad, podgorica, ...) are
# omitted — bookaway_city_en() returns the slug unchanged. Extend when the
# verifier (scripts/verify_bookaway_pairs.py) reports zero-verified cities.
BOOKAWAY_CITY_SLUG_EN: dict[str, str] = {
    'beograd': 'belgrade',
}


def bookaway_city_en(slug: str) -> str:
    """Map our city slug to Bookaway's English slug (identity if not overridden)."""
    return BOOKAWAY_CITY_SLUG_EN.get(slug, slug)


