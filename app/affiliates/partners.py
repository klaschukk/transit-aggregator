class Bookaway(Partner):
    """Primary partner. Strongest Balkans coverage, highest commission band."""
    key = 'bookaway'
    name = 'Bookaway'
    # Bookaway brand is emerald-600 (#059669); at 13.6 px normal white its
    # ratio on white text is 3.76:1 (WCAG AA fail). Stepping down one tone
    # to emerald-700 (#047857) clears 4.65:1 and is virtually indistinguishable
    # to the eye — and matches the old :hover, so there's no flicker. The
    # primary revenue CTA must pass AA first; brand exactness second.
    brand_color = '#047857'
    commission_band = (5.0, 10.0)
    ux_rank = 1

    OFFER_ID = 34       # approved
    AFF_ID = 4033       # approved
    # TUNE/HasOffers click-tracking host for this network. Links MUST go
    # through it (aff_c) — that's what mints the transaction_id and sets the
    # enc_aff_session cookie the conversion postback keys off. Pointing
    # straight at bookaway.com with ?offer_id/?aff_id as plain query params
    # does NOT register a click, so conversions can never be attributed
    # (root cause of "362 clicks, 0 conversions" — Bookaway audit, Jun 2026).
    TRACKING_HOST = 'bookaway2.go2cloud.org'

    def has_route(self, from_slug: str, to_slug: str) -> bool:
        # FAR-ONLY (owner decision 2026-06-10): Bookaway is used ONLY for
        # far/long-haul destinations (Asia, Middle East, …) we have no local
        # data for — the AI-itinerary search fallback. Every regular Balkan
        # route goes to BusTicket4; Bookaway must never surface there. So a pair
        # is Bookaway-eligible only when one endpoint is a far destination.
        # build_url still resolves the country via the (far-augmented)
        # _BOOKAWAY_COUNTRY_MAP, so the Asia listing URL stays correct.
        return from_slug in FAR_DESTINATIONS or to_slug in FAR_DESTINATIONS

    def build_url(
        self,
        from_slug: str,
        to_slug: str,
        from_city: str,
        to_city: str,
        utm_medium: str,
    ) -> str:
        from_country = _BOOKAWAY_COUNTRY_MAP.get(from_slug)
        to_country = _BOOKAWAY_COUNTRY_MAP.get(to_slug)
        # Exact pair deep-link ONLY for pairs verified to return 200 on Bookaway
        # (scripts/verify_bookaway_pairs.py -> bookaway_pairs.json). Bookaway's
        # pair pages use English slugs under the departure country (belgrade,
        # not beograd) and only exist where it actually sells the route, so an
        # unverified guess 404s — the user lands on an error page (zero
        # conversions despite a tracked click: the original "362 clicks, 0
        # conversions" failure). Verified pairs land on the exact route (best
        # conversion); everything else falls back to the always-200 country page.
        if from_country and f'{from_slug}:{to_slug}' in _VERIFIED_PAIRS:
            path = (
                f'/routes/{from_country}/'
                f'{bookaway_city_en(from_slug)}-to-{bookaway_city_en(to_slug)}'
            )
        else:
            country = to_country or from_country or 'serbia'
            path = f'/routes/{country}/'
        dest = (
            f'https://www.bookaway.com{path}'
            f'?utm_source=prevozni&utm_medium={utm_medium}'
        )
        # Route through the TUNE tracker. aff_sub/aff_sub2 give per-route and
        # per-surface conversion attribution in the affiliate reports without
        # any panel change. `url` carries the (encoded) deep-link destination.
        aff_sub = f'{from_slug}-{to_slug}'[:255]
        return (
            f'https://{self.TRACKING_HOST}/aff_c'
            f'?offer_id={self.OFFER_ID}&aff_id={self.AFF_ID}'
            f'&aff_sub={quote(aff_sub, safe="")}'
            f'&aff_sub2={quote(utm_medium, safe="")}'
            f'&url={quote(dest, safe="")}'
        )


# ── BusTicket4 — primary partner, also our intercity data source ───
class BusTicket4(Partner):
    """busticket4.me — the operator whose API feeds our intercity routes, and
    now an affiliate partner (affiliateId 735 for prevozni.com, Cassiopeia doo).
    IMPORTANT: a busticket4 checkout needs a `line_id` (a specific departure) —
    without one the page renders an empty 0.00 € shell. So BusTicket4 is NOT a
    generic pair-level partner (it is kept OUT of ACTIVE_PARTNERS). It is wired
    per-trip: the buy button upgrades to bt4_checkout_url(from, to, line_id)
    only for departures whose busticket4 line_id we know (trips.bt4_line_id),
    which yields the EXACT trip + price + a clean affiliateId attribution. Pair
    surfaces with no line_id fall back to Bookaway."""
    key = 'busticket4'
    name = 'BusTicket4'
    # busticket4 brand is green; green-800 (#166534) clears WCAG AA (~6:1) for
    # white button text, where their lighter brand green would fail.
    brand_color = '#166534'
    commission_band = (2.0, 2.0)  # 2% of every ticket sold (Cassiopeia agreement)
    ux_rank = 0

    AFFILIATE_ID = 735  # prevozni.com

    def has_route(self, from_slug: str, to_slug: str) -> bool:
        # PAIR-level eligibility (what the resolver's "Kupi" button uses): we
        # need a known line_id for the pair AND both numeric city_ids, so the
        # checkout deep-link is guaranteed to open a populated departure rather
        # than an empty 0.00 € shell. Pairs missing either fall through to
        # Bookaway. (The per-trip buy button is separate — see bt4_checkout_url,
        # which deep-links each trip's own line_id and does its own guarding.)
        return (
            f'{from_slug}-{to_slug}' in _BT4_PAIR_LINEID
            and from_slug in _BT4_CITY_ID
            and to_slug in _BT4_CITY_ID
        )

    def build_url(
        self,
        from_slug: str,
        to_slug: str,
        from_city: str,
        to_city: str,
        utm_medium: str,
        line_id: int | None = None,
        depart_date: str | None = None,
    ) -> str:
        dep = _BT4_CITY_ID[from_slug]
        arr = _BT4_CITY_ID[to_slug]
        # Pair-level callers (make_offer) pass no line_id — fall back to the
        # pre-resolved pair line_id so the checkout still selects a real
        # departure. Per-trip callers pass the trip's exact line_id and win.
        if line_id is None:
            line_id = _BT4_PAIR_LINEID.get(f'{from_slug}-{to_slug}')
        # Prefer the date the user actually searched for (search form's
        # YYYY-MM-DD `datum`) so the checkout opens on their travel day instead
        # of making them re-pick it. Fall back to tomorrow so an
        # overnight-cached page never points at a past date (busticket4 wants
        # DD-MM-YYYY). The user can still change it on checkout.
        depart = ''
        if depart_date:
            try:
                _d = date.fromisoformat(str(depart_date)[:10])
                if _d >= date.today():
                    depart = _d.strftime('%d-%m-%Y')
            except ValueError:
                pass
        if not depart:
            depart = (date.today() + timedelta(days=1)).strftime('%d-%m-%Y')
        # affiliateId is the attribution — no separate click-tracker hop needed.
        url = (
            'https://busticket4.me/en/checkout'
            f'?departureCityId={dep}&arrivalCityId={arr}'
            f'&departureDate={depart}&passengers=1'
            f'&tripType=one-way&affiliateId={self.AFFILIATE_ID}'
        )
        # lineId selects the exact departure; without it the checkout is empty.
        if line_id:
            url += f'&lineId={int(line_id)}'
        return url


# Single shared instance for the per-trip Jinja helper below.
_BT4 = BusTicket4()


def _now_belgrade():
    from datetime import datetime
    from zoneinfo import ZoneInfo
    return datetime.now(ZoneInfo('Europe/Belgrade'))


def bt4_line_for(from_slug: str, to_slug: str, dep_time) -> int | None:
    """BusTicket4 lineId of the departure at `dep_time` ('HH:MM…') on this
    pair, or None when BT4 has no purchasable departure at exactly that time."""
    if not dep_time:
        return None
    return _BT4_DEPARTURES.get(f'{from_slug}-{to_slug}', {}).get(str(dep_time)[:5])


def bt4_checkout_url(from_slug: str, to_slug: str, line_id, depart_date=None, dep_time=None) -> str:
    """Exact busticket4 affiliate checkout for ONE departure, or '' if we can't
    build it (unknown city or missing line_id). Exposed as a Jinja global so the
    per-trip buy button can deep-link straight to that trip's checkout.
    depart_date (YYYY-MM-DD, e.g. the search form's `datum` or the route page's
    day tab) presets the checkout to the user's travel day; omitted/past dates
    fall back to tomorrow. With dep_time ('HH:MM') a missing date means today
    (Serbia), and a departure that already left today rolls to tomorrow."""
    if not line_id or from_slug not in _BT4_CITY_ID or to_slug not in _BT4_CITY_ID:
        return ''
    if dep_time:
        now = _now_belgrade()
        try:
            day = date.fromisoformat(str(depart_date)[:10]) if depart_date else now.date()
        except ValueError:
            day = now.date()
        if day == now.date() and str(dep_time)[:5] <= now.strftime('%H:%M'):
            day += timedelta(days=1)
        depart_date = day.isoformat()
    return _BT4.build_url(from_slug, to_slug, '', '', 'trip-card',
                          line_id=line_id, depart_date=depart_date)


